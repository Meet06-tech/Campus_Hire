CREATE TABLE password_change_otps (
    password_change_otp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    otp_hash VARCHAR(100) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    verified_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    CONSTRAINT password_change_otps_user_fk FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT password_change_otps_attempts_ck CHECK (attempts >= 0 AND attempts <= 5)
);

CREATE INDEX password_change_otps_user_idx ON password_change_otps(user_id, requested_at DESC);
