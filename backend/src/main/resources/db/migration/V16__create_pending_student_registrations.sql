CREATE TABLE pending_student_registrations (
    pending_registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    enrollment_number VARCHAR(80) NOT NULL UNIQUE,
    university_email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    department_id BIGINT NOT NULL,
    otp_hash VARCHAR(100) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    verified_at TIMESTAMPTZ,
    consumed_at TIMESTAMPTZ,
    CONSTRAINT pending_student_registrations_department_fk
        FOREIGN KEY (department_id) REFERENCES departments(department_id),
    CONSTRAINT pending_student_registrations_attempts_ck
        CHECK (attempts >= 0 AND attempts <= 5)
);

CREATE INDEX pending_student_registrations_requested_idx
    ON pending_student_registrations(requested_at DESC);
