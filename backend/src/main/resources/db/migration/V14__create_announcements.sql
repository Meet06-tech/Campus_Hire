CREATE TABLE announcements (
    announcement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(200) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    publisher_user_id BIGINT NOT NULL,
    department_id BIGINT,
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT announcements_publisher_fk FOREIGN KEY (publisher_user_id) REFERENCES users(user_id),
    CONSTRAINT announcements_department_fk FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE INDEX announcements_published_at_idx ON announcements(published_at DESC, announcement_id DESC);
CREATE INDEX announcements_department_idx ON announcements(department_id, published_at DESC, announcement_id DESC);
